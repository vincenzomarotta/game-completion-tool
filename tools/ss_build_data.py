# Build silksong/data.js: every tracked item (silksong-completionist dictionary, MIT) with a map position when the
# game files tell us where it is (scene object position from ss_scan_scenes.py mapped onto the room sprite).
import json, os, re, shutil, sys

OUT = sys.argv[1]
d = json.load(open("ss/dict.json"))
rooms = json.load(open("ss_rooms.json"))
scenes = json.load(open("ss_scenes.json"))
best = json.load(open("ss_bestiary_index.json"))
S = rooms["scale"]
room_ci = {k.lower(): v for k, v in rooms["rooms"].items()}

AREA = {
    "Tut": "Moss Grotto", "Bonetown": "Bone Bottom", "Bone": "The Marrow", "Crawl": "Wormways", "Dock": "Deep Docks",
    "Weavehome": "Weavenest", "Ant": "Hunter's March", "Wilds": "Far Fields", "Greymoor": "Greymoor", "Dust": "Sinner's Road",
    "Dust Maze": "The Mist", "Wisp": "Wisp Thicket", "Swamp": "Bilewater", "Aqueduct": "Putrified Ducts", "Belltown": "Bellhart",
    "Shellwood": "Shellwood", "Blasted_Steps": "Blasted Steps", "Coral_Caves": "Sands of Karak", "Slab": "The Slab",
    "Peak": "Mount Fay", "Song": "Choral Chambers", "Song_Gate": "Grand Gate", "Under": "Underworks", "Library": "Whispering Vaults",
    "Cog": "Cogwork Core", "Ward": "Whiteward", "Hang": "High Halls", "Arborium": "Memorium", "Cradle": "The Cradle",
    "Clover": "Verdania", "Abyss": "The Abyss", "Surface": "Surface",
}
# category -> (key, pin icon); a section can override the icon
CATS = {
    "Mask Shards": "mask", "Spool Fragments": "spool", "Memory Lockets": "locket", "Craftmetals": "metal", "Mossberries": "berry",
    "Pale Oil": "core", "Silkeaters": "silkeater", "Caches & Secrets": "rosary", "Unique Spawns": "beast", "Keys": "key",
    "Upgrades": "core", "Lost Fleas": "flea",
}
SECTION_PIN = {"Shell Shard Caches": "shard", "Breakable Walls": "wall", "Void Masses": "void"}

def infos(p): return p if isinstance(p, list) else [p]

def place(scene, obj):
    """Map pixel position of an object in a scene, or the room position when the object/scene size is unknown."""
    room = rooms["rooms"].get(scene) or room_ci.get(scene.lower())
    if not room:
        return None
    x, y, area, w, h, pvx, pvy = room
    info = scenes.get(scene) or {}
    pos = info.get("objs", {}).get(obj)
    if pos and info.get("size"):
        W, H = info["size"]
        left, bottom = x - pvx * w * S, y + pvy * h * S
        return [round(left + pos[0] / W * w * S), round(bottom - pos[1] / H * h * S)], AREA.get(area, area)
    return [round(x + (0.5 - pvx) * w * S), round(y - (0.5 - pvy) * h * S)], AREA.get(area, area)

items, journal = [], []
os.makedirs(os.path.join(OUT, "journal"), exist_ok=True)
for cat in d:
    for sec in cat["sections"]:
        for it in sec["items"]:
            ps = infos(it["parsingInfo"])
            if cat["name"] == "Hunter's Journal":
                jid = ps[0]["internalId"]
                rec = {"n": it["name"], "id": jid, "k": (it.get("additionalMeta") or {}).get("killsRequired", 1),
                       "m": it.get("mapLink", ""), "d": it.get("completionDetails", "")}
                if jid in best["index"]:
                    rec["i"] = best["index"][jid]
                else:  # no icon in the game atlas: fall back to the dictionary's image
                    src = os.path.join("ss/silksong-completionist/src/assets", it["additionalMeta"]["imageAsset"])
                    shutil.copy(src, os.path.join(OUT, "journal", os.path.basename(src)))
                    rec["img"] = "journal/" + os.path.basename(src)
                journal.append(rec)
                continue
            rec = {"c": cat["name"], "s": sec.get("name") or "", "n": it["name"], "d": it.get("completionDetails", ""),
                   "m": it.get("mapLink", ""), "a": it.get("whichAct", 0), "t": it["parsingInfo"]}
            if it.get("onlyFoundInSteelSoulMode"): rec["ss"] = 1
            if it.get("onlyFoundInClassicMode"): rec["cl"] = 1
            pin = None
            for p in ps:
                if p["type"].startswith("sceneData"):
                    pin = place(p["internalId"][0], p["internalId"][1]); break
                if p["type"] == "flag" and p["internalId"].startswith("SavedFlea_"):
                    pin = place(p["internalId"][len("SavedFlea_"):], "*flea*"); break
            if pin and cat["name"] in CATS:
                rec["p"], rec["r"] = pin
                rec["i"] = SECTION_PIN.get(sec.get("name"), CATS[cat["name"]])
            items.append(rec)

meta = {"size": rooms["size"], "cell": best["cell"], "cols": best["cols"]}
with open(os.path.join(OUT, "data.js"), "w", encoding="utf8") as f:
    f.write("// Item list and save rules from Br3zzly/silksong-completionist (MIT); positions from the game files.\n")
    f.write("// Generated by tools/ss_build_data.py. Do not edit by hand.\n")
    f.write("window.SS = " + json.dumps({**meta, "items": items, "journal": journal}, ensure_ascii=False, separators=(",", ":")) + ";\n")
pinned = sum(1 for i in items if "p" in i)
print(len(items), "items,", pinned, "on the map,", len(journal), "journal entries")
