# Build hollow-knight/achievements.js (keys, hidden flag, EN/IT name and text in the game's order) + achievements.webp (icon sheet).
import UnityPy, base64, re, json, sys, os, html, warnings
from UnityPy.helpers.TypeTreeGenerator import TypeTreeGenerator
from Crypto.Cipher import AES
from PIL import Image
warnings.filterwarnings("ignore")

GAME = r"C:\Program Files (x86)\Steam\steamapps\common\Hollow Knight"
OUT, CELL, COLS = sys.argv[1], 64, 10
env = UnityPy.load(GAME + r"\hollow_knight_Data\resources.assets")
gen = TypeTreeGenerator(env.objects[0].assets_file.unity_version)
gen.load_local_game(GAME)
env.typetree_generator = gen

def sheet(lang, name):
    o = next(o for o in env.objects if o.type.name == "TextAsset" and o.peek_name() == f"{lang}_{name}")
    s = o.read().m_Script
    s = s if isinstance(s, str) else s.decode("utf8", "surrogateescape")
    raw = AES.new(b"UKu52ePUBwetZ9wNX88o54dnfKRu0T1l", AES.MODE_ECB).decrypt(base64.b64decode(s))
    raw = raw[:-raw[-1]].decode("utf8")
    return {k: html.unescape(re.sub(r"<[^>]+>", "", v)).strip() for k, v in re.findall(r'<entry name="([^"]+)">(.*?)</entry>', raw, re.S)}

EN, IT = sheet("EN", "Achievements"), sheet("IT", "Achievements")
objs = {o.path_id: o for o in env.objects}
lst = next(o.parse_as_dict() for o in env.objects if o.type.name == "MonoBehaviour" and o.peek_name() == "Achievements List")["achievements"]
img = Image.new("RGBA", (COLS * CELL, -(-len(lst) // COLS) * CELL))
out = []
for i, a in enumerate(lst):
    ic = objs[a["earnedIcon"]["m_PathID"]].read().image
    ic.thumbnail((CELL, CELL), Image.LANCZOS)
    img.paste(ic, ((i % COLS) * CELL + (CELL - ic.width) // 2, (i // COLS) * CELL + (CELL - ic.height) // 2))
    out.append({"k": a["key"], "h": a["type"], "n": [EN[a["localizedTitle"]], IT[a["localizedTitle"]]], "d": [EN[a["localizedText"]], IT[a["localizedText"]]]})
img.save(os.path.join(OUT, "achievements.webp"), quality=90)
with open(os.path.join(OUT, "achievements.js"), "w", encoding="utf8") as f:
    f.write("// Achievements, names and icons from the game files. Generated by tools/hk_build_achievements.py. Do not edit by hand.\n")
    f.write("window.ACH = " + json.dumps({"cell": CELL, "cols": COLS, "list": out}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(out), "achievements")
