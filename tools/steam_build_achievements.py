# Build <game>/achievements.js + achievements.webp from the game's public Steam achievements page (EN and IT text, icons).
# Usage: steam_build_achievements.py <appid> <out dir>
import json, os, re, sys, io, urllib.request
from PIL import Image

APP, OUT, CELL, COLS = sys.argv[1], sys.argv[2], 64, 10

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=30).read()

def achievements(lang):
    page = get(f"https://steamcommunity.com/stats/{APP}/achievements/?l={lang}").decode("utf8")
    page = page.replace('\\"', '"').replace("\\\\", "\\")
    seen, out = set(), []
    for m in re.finditer(r'\{"internal_key":\d+,"api_name":"([^"]+)","name":"((?:[^"\\]|\\.)*)","description":"((?:[^"\\]|\\.)*)","hidden":(true|false),"archived":(true|false),"icon_achieved":"([^"]+)"', page):
        key = m.group(1)
        if key in seen or m.group(5) == "true":
            continue
        seen.add(key)
        txt = lambda s: json.loads('"' + s + '"')
        out.append({"k": key, "name": txt(m.group(2)), "desc": txt(m.group(3)), "h": int(m.group(4) == "true"), "icon": m.group(6)})
    return out

en, it = achievements("english"), {a["k"]: a for a in achievements("italian")}
img = Image.new("RGBA", (COLS * CELL, -(-len(en) // COLS) * CELL))
rows = []
for i, a in enumerate(en):
    ic = Image.open(io.BytesIO(get(a["icon"]))).convert("RGBA").resize((CELL, CELL), Image.LANCZOS)
    img.paste(ic, ((i % COLS) * CELL, (i // COLS) * CELL))
    b = it.get(a["k"], a)
    rows.append({"k": a["k"], "h": a["h"], "n": [a["name"], b["name"]], "d": [a["desc"], b["desc"]]})
img.save(os.path.join(OUT, "achievements.webp"), quality=90)
with open(os.path.join(OUT, "achievements.js"), "w", encoding="utf8") as f:
    f.write(f"// Achievements and icons from the game's Steam page (app {APP}). Generated by tools/steam_build_achievements.py. Do not edit by hand.\n")
    f.write("window.ACH = " + json.dumps({"cell": CELL, "cols": COLS, "list": rows}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(rows), "achievements")
for r in rows:
    print(r["k"], r["h"], "|", r["n"][0], "|", r["d"][0], "|", r["n"][1], "|", r["d"][1])
