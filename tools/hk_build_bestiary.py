# Build the Hunter's Journal data for hollow-knight/: bestiary.js (entries in journal order) + bestiary.webp (portrait sheet).
# Needs the game installed, UnityPy + TypeTreeGeneratorAPI + pycryptodome + Pillow, and ReznoR's hk-database.js for kill counts/areas.
import UnityPy, base64, re, json, sys, os, html
from UnityPy.helpers.TypeTreeGenerator import TypeTreeGenerator
from Crypto.Cipher import AES
from PIL import Image

GAME = r"C:\Program Files (x86)\Steam\steamapps\common\Hollow Knight"
OUT = sys.argv[1]
CELL = 96

env = UnityPy.load(GAME + r"\hollow_knight_Data\resources.assets")
gen = TypeTreeGenerator(env.objects[0].assets_file.unity_version)
gen.load_local_game(GAME)
env.typetree_generator = gen

def sheet(lang, name):
    o = next(o for o in env.objects if o.type.name == "TextAsset" and o.peek_name() == f"{lang}_{name}")
    s = o.read().m_Script
    s = s if isinstance(s, str) else s.decode("utf8", "surrogateescape")
    raw = AES.new(b"UKu52ePUBwetZ9wNX88o54dnfKRu0T1l", AES.MODE_ECB).decrypt(base64.b64decode(s))
    raw = raw[:-raw[-1]].decode("utf8")
    return {k: html.unescape(re.sub(r"<[^>]+>", "", v)).strip() for k, v in re.findall(r'<entry name="([^"]+)">(.*?)</entry>', raw, re.S)}

EN, IT = sheet("EN", "Journal"), sheet("IT", "Journal")
KILLS = json.load(open("hk_kills.json"))  # from tools/hk_kill_counts.py: default kills<Enemy> = kills needed

# ReznoR's database: per playerDataName, "Name (kills)" plus an area hint and wiki slug.
db = open("hk/hollow-knight-completion-check/src/js/hk-database.js", encoding="utf8").read()
rez = {}
for m in re.finditer(r'\n\s+(\w+): \{\s*name: "([^"]*)",\s*nameDefault: "[^"]*",\s*spoiler: "([^"]*)",\s*wiki: "([^"]*)"', db):
    k = re.search(r"\((\d+)\)\s*$", m.group(2))
    rez[m.group(1)] = (int(k.group(1)) if k else 1, m.group(3), m.group(4))

# JournalList.list holds the entry GameObjects in the order the journal shows them.
journal_order = {}
for o in env.objects:
    if o.type.name == "MonoBehaviour":
        try:
            d = o.parse_as_dict()
        except Exception:
            continue
        if "list" in d and "listInv" in d and len(d["list"]) > 100:
            journal_order = {p["m_PathID"]: i for i, p in enumerate(d["list"])}
            break

entries = []
for o in env.objects:
    if o.type.name != "MonoBehaviour":
        continue
    try:
        d = o.parse_as_dict()
    except Exception:
        continue
    if "playerDataName" not in d or "convoName" not in d:
        continue
    order = journal_order.get(d["m_GameObject"]["m_PathID"], 9999)
    spr = None
    if d["sprite"]["m_PathID"]:
        spr = next(x for x in env.objects if x.path_id == d["sprite"]["m_PathID"]).read()
    entries.append((order, d, spr))

entries.sort(key=lambda e: e[0])
seen, uniq = set(), []
for e in entries:
    if e[1]["playerDataName"] not in seen:
        seen.add(e[1]["playerDataName"]); uniq.append(e)
entries = uniq
entries = [e for e in entries if e[0] < 9999]
cols = 14
rows = (len(entries) + cols - 1) // cols
img = Image.new("RGBA", (cols * CELL, rows * CELL), (0, 0, 0, 0))
out = []
for n, (order, d, spr) in enumerate(entries):
    if spr:
        im = spr.image.convert("RGBA")
        im.thumbnail((CELL - 4, CELL - 4), Image.LANCZOS)
        img.alpha_composite(im, ((n % cols) * CELL + (CELL - im.width) // 2, (n // cols) * CELL + (CELL - im.height) // 2))
    pd = d["playerDataName"]
    _, area, wiki = rez.get(pd, (None, "", ""))
    # The game reads killed<Name>/kills<Name>; some DLC entries carry placeholder field names in the asset.
    kills = KILLS.get("kills" + pd, 1)
    out.append({"id": pd, "en": EN.get(d["nameConvo"], pd), "it": IT.get(d["nameConvo"], EN.get(d["nameConvo"], pd)),
                "k": kills, "a": area, "w": wiki})

img.save(os.path.join(OUT, "bestiary.webp"), quality=85, method=6)
with open(os.path.join(OUT, "bestiary.js"), "w", encoding="utf8") as f:
    f.write("// Hunter's Journal entries in journal order. Names from the game, kill counts and areas from\n")
    f.write("// ReznoRMichael/hollow-knight-completion-check (GPL-3.0). Generated by tools/hk_build_bestiary.py.\n")
    f.write("window.HK_BESTIARY = " + json.dumps({"cell": CELL, "cols": cols, "entries": out}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(out), "entries; no area hint for:", [e["id"] for e in out if not e["a"]])

# Knight icon for the home page card.
k = next(o for o in env.objects if o.type.name == "Sprite" and o.peek_name() == "knight_icon").read()
k.image.save(os.path.join(OUT, "knight.png"))
print("knight icon", k.image.size)
