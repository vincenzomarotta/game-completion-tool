# Build silksong/achievements.js (keys, hidden flag, EN/IT name and text in the game's order) + achievements.webp (icon sheet).
import json, os, sys, base64, re, html, warnings
warnings.filterwarnings("ignore")
sys.path.insert(0, ".")
from ss_env import *
from Crypto.Cipher import AES
from PIL import Image

OUT, CELL, COLS = sys.argv[1], 64, 10
env = UnityPy.load(AA + r"\dataassets_assets_assets\dataassets\achievementslist.asset.bundle",
                   AA + r"\atlases_assets_assets\sprites\_atlases\achievement_icons_hornet.spriteatlas.bundle")
res = UnityPy.load(DATA + r"\resources.assets")

def sheet(lang, name):
    o = next(o for o in res.objects if o.type.name == "TextAsset" and o.peek_name() == f"{lang}_{name}")
    s = o.read().m_Script
    s = s if isinstance(s, (bytes, bytearray)) else s.encode("utf-8", "surrogateescape")
    raw = AES.new(b"UKu52ePUBwetZ9wNX88o54dnfKRu0T1l", AES.MODE_ECB).decrypt(base64.b64decode(s))
    raw = raw[:-raw[-1]].decode("utf8")
    return {k: re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", html.unescape(v))).strip() for k, v in re.findall(r'<entry name="([^"]+)">(.*?)</entry>', raw, re.S)}

EN, IT = sheet("EN", "Achievements"), sheet("IT", "Achievements")
sprites = {o.path_id: o for o in env.objects if o.type.name == "Sprite"}
lst = next(o.parse_as_dict() for o in env.objects if o.type.name == "MonoBehaviour")["achievements"]
img = Image.new("RGBA", (COLS * CELL, -(-len(lst) // COLS) * CELL))
out = []
for i, a in enumerate(lst):
    k = a["PlatformKey"]
    ic = sprites[a["Icon"]["m_PathID"]].read().image
    ic.thumbnail((CELL, CELL), Image.LANCZOS)
    img.paste(ic, ((i % COLS) * CELL + (CELL - ic.width) // 2, (i // COLS) * CELL + (CELL - ic.height) // 2))
    out.append({"k": k, "h": a["Type"], "n": [EN[k + "_NAME"], IT[k + "_NAME"]], "d": [EN[k + "_DESC"], IT[k + "_DESC"]]})
img.save(os.path.join(OUT, "achievements.webp"), quality=90)
with open(os.path.join(OUT, "achievements.js"), "w", encoding="utf8") as f:
    f.write("// Achievements, names and icons from the game files. Generated by tools/ss_build_achievements.py. Do not edit by hand.\n")
    f.write("window.ACH = " + json.dumps({"cell": CELL, "cols": COLS, "list": out}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(out), "achievements")
